/** Тесттің сұрақтар қоры (қорытынды емтихан үшін — басқа тесттерден). */
export function questionPool(test) {
  if (!test.pools) return test.questions;
  return test.pools.flatMap((id) => testById(id)?.questions || []);
}

export function questionById(id) {
  for (const t of TESTS) {
    const q = t.questions.find((x) => x.id === id);
    if (q) return q;
  }
  return null;
}
